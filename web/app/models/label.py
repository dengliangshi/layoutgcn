# -----------------------------------------------------------Main-----------------------------------------------------------
class Label(db.Model):

    __tablename__ = "label"

    id = db.Column(db.String(64), primary_key=True)
    name = db.Column(db.Text)

    def __init__(self, **kwargs):
        super(Label, self).__init__(**kwargs)

    def __repr__(self):
        return "<Label %r>" % self.id
